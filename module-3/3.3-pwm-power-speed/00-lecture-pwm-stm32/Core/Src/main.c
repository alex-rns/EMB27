/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM1_Init();
  MX_ADC1_Init();
  /* USER CODE BEGIN 2 */
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);           // CH1 on PA8
  HAL_TIMEx_PWMN_Start(&htim1, TIM_CHANNEL_1);        // CH1N on PA7: the complementary (inverted) output
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, 250);  // CCR1 = 250 of ARR + 1 = 1000: 25 % until the first ADC result
  HAL_ADC_Start_IT(&hadc1);  // ADC on with the end-of-conversion interrupt; continuous mode: it keeps converting
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  uint16_t adc_corrected = 0;
  while (1)
  {
    if (adc_ready == 1u)  // the ADC interrupt left a new result
    {
      // the potentiometer 0..4000 -> CCR 0..1000 = 0..100 % duty (ARR + 1 = 1000)
      adc_corrected = (adc_value > 4000u) ? 1000u : (uint16_t)(adc_value / 4u);
      __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, adc_corrected);
      adc_ready = 0u;  // result taken
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

